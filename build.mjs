// Encrypts the dashboard (src/data.js + src/app.js) into assets/secure.js.
//
// Usage (Node 18+, no packages needed):
//   node build.mjs                 # asks for the password
//   SITE_PASSWORD='...' node build.mjs
//
// Run this after every edit to src/, then commit assets/secure.js.
// The password is never written to disk.

import { readFileSync, writeFileSync } from "node:fs";
import { randomBytes, pbkdf2Sync, createCipheriv } from "node:crypto";
import { createInterface } from "node:readline";

const ITERATIONS = 250000;

async function askPassword() {
  if (process.env.SITE_PASSWORD) return process.env.SITE_PASSWORD;
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const pw = await new Promise((res) => rl.question("Site password: ", res));
  rl.close();
  return pw;
}

const password = await askPassword();
if (!password) { console.error("No password given."); process.exit(1); }

const code = ["src/data.js", "src/app.js"].map((f) => readFileSync(f, "utf8")).join("\n;\n");

const salt = randomBytes(16);
const iv = randomBytes(12);
const key = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
const cipher = createCipheriv("aes-256-gcm", key, iv);
const ct = Buffer.concat([cipher.update(code, "utf8"), cipher.final(), cipher.getAuthTag()]);

const out = `// Encrypted dashboard — generated by build.mjs. Do not edit by hand.
window.ENCRYPTED = ${JSON.stringify({
  iter: ITERATIONS,
  salt: salt.toString("base64"),
  iv: iv.toString("base64"),
  data: ct.toString("base64"),
})};
`;
writeFileSync("assets/secure.js", out);
console.log(`Wrote assets/secure.js (${(ct.length / 1024).toFixed(1)} KB encrypted).`);
