// Builds the site from src/ (Node 18+, no packages needed).
//
//   node build.mjs                          # asks for the site password
//   SITE_PASSWORD='...' node build.mjs
//   node build.mjs --new-password           # deliberately change the site password
//
// It writes two encrypted files, both safe to commit to the public repo:
//   assets/secure.js : the dashboard (src/data.js + src/app.js), unlocked in the browser
//   src.enc          : an encrypted backup of the whole src/ folder, so the next maintainer
//                      can restore it with `node unpack.mjs` and the same password
// The password is never written to disk.

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { randomBytes, pbkdf2Sync, createCipheriv, createDecipheriv } from "node:crypto";
import { createInterface } from "node:readline";

const ITERATIONS = 250000;
const changing = process.argv.includes("--new-password");

async function ask(q) {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const a = await new Promise((res) => rl.question(q, res));
  rl.close();
  return a;
}

function encrypt(text, password) {
  const salt = randomBytes(16), iv = randomBytes(12);
  const key = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
  const c = createCipheriv("aes-256-gcm", key, iv);
  const ct = Buffer.concat([c.update(text, "utf8"), c.final(), c.getAuthTag()]);
  return { iter: ITERATIONS, salt: salt.toString("base64"), iv: iv.toString("base64"), data: ct.toString("base64") };
}

function decrypts(box, password) {
  try {
    const key = pbkdf2Sync(password, Buffer.from(box.salt, "base64"), box.iter, 32, "sha256");
    const buf = Buffer.from(box.data, "base64");
    const d = createDecipheriv("aes-256-gcm", key, Buffer.from(box.iv, "base64"));
    d.setAuthTag(buf.subarray(buf.length - 16));
    Buffer.concat([d.update(buf.subarray(0, buf.length - 16)), d.final()]);
    return true;
  } catch { return false; }
}

const password = process.env.SITE_PASSWORD || await ask(changing ? "NEW site password: " : "Site password: ");
if (!password) { console.error("No password given."); process.exit(1); }

// Safety: don't silently change the password everyone uses
if (existsSync("assets/secure.js")) {
  const m = readFileSync("assets/secure.js", "utf8").match(/window\.ENCRYPTED = (\{[\s\S]*?\});/);
  const current = m && JSON.parse(m[1]);
  if (current && !decrypts(current, password)) {
    if (!changing) {
      console.error("That isn't the current site password, so nothing was built.\n" +
        "Typo? Just run it again. Changing the password on purpose? Run: node build.mjs --new-password");
      process.exit(1);
    }
    const again = process.env.SITE_PASSWORD ? password : await ask("Type the NEW password again: ");
    if (again !== password) { console.error("The two passwords don't match. Nothing was built."); process.exit(1); }
    console.log("Changing the site password. Tell the committee the new one.");
  }
}

// 1) the dashboard
const code = ["src/data.js", "src/app.js"].map((f) => readFileSync(f, "utf8")).join("\n;\n");
const box = encrypt(code, password);
writeFileSync("assets/secure.js", `// Encrypted dashboard — generated by build.mjs. Do not edit by hand.\nwindow.ENCRYPTED = ${JSON.stringify(box)};\n`);
console.log(`Wrote assets/secure.js (${(Buffer.from(box.data, "base64").length / 1024).toFixed(1)} KB encrypted).`);

// 2) encrypted backup of the whole src/ folder
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name === ".DS_Store") continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p); else files[p.split("\\").join("/")] = readFileSync(p, "utf8");
  }
})("src");
const backup = encrypt(JSON.stringify({ created: new Date().toISOString(), files }), password);
writeFileSync("src.enc", JSON.stringify({ about: "Encrypted copy of src/. Restore with: node unpack.mjs", ...backup }) + "\n");
console.log(`Wrote src.enc (encrypted backup of ${Object.keys(files).length} files in src/).`);
console.log("Next: git add . && git commit -m \"…\" && git push");
